export function getRealFestivalsForMonth(year: number, month: number, categoryFilter?: string, searchQuery?: string): RealFestivalItem[] {
  let list = MASTER_FESTIVALS_DB.filter((item) => {
    const d = new Date(item.date)
    return d.getUTCFullYear() === year && d.getUTCMonth() + 1 === month
  })

  // Filter by Category
  if (categoryFilter && categoryFilter !== 'ALL') {
    const cat = categoryFilter.toLowerCase()
    list = list.filter(
      (item) =>
        item.category.toLowerCase().includes(cat) ||
        item.categoryHi.toLowerCase().includes(cat)
    )
  }

  // Filter by Search Query
  if (searchQuery) {
    const q = searchQuery.toLowerCase()
    list = list.filter(
      (item) =>
        item.festival.toLowerCase().includes(q) ||
        item.festivalHi.toLowerCase().includes(q) ||
        item.significance.toLowerCase().includes(q) ||
        item.significanceHi.toLowerCase().includes(q)
    )
  }

  return list
}
